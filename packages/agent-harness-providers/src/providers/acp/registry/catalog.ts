// ────────────────────────────────────────────────────────────────
// The ACP Registry catalogue, cached on disk (docs/acp ACP-4, ACP-5).
//
// - Source: `https://cdn.agentclientprotocol.com/registry/v1/latest/registry.json`,
//   or `GENERATORAI_ACP_REGISTRY_URL` (tests, air-gapped installs).
// - Cache: `<cacheDir>/registry.json` (the raw body), `meta.json` (etag,
//   fetchedAt, checkedAt, url) and `icons.json` (sanitised marks by agent id,
//   with the URL each came from). Written atomically (tmp + rename).
// - Refresh: at most hourly unless forced (the Settings "Refresh" button),
//   with `If-None-Match`; 30 s for the index, 10 s per icon. A failed refresh
//   keeps the cache and reports the error.
// - Fallback: the bundled snapshot (`snapshot/*.json`, regenerated by
//   `scripts/acp/update-registry-snapshot.mjs`) when there is no cache.
// ────────────────────────────────────────────────────────────────

import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { ProviderMark } from '@generatorai/shared';
import { sanitizeSvgIcon, MAX_ICON_BYTES } from './iconSanitizer.js';
import { parseAcpRegistry, type AcpRegistryIndex } from './schema.js';

export const ACP_REGISTRY_URL = 'https://cdn.agentclientprotocol.com/registry/v1/latest/registry.json';
export const ACP_REGISTRY_URL_ENV = 'GENERATORAI_ACP_REGISTRY_URL';
/** At most one network refresh per hour unless forced (Zed's throttle). */
export const ACP_REGISTRY_REFRESH_MS = 60 * 60_000;
const FETCH_TIMEOUT_MS = 30_000;
const ICON_TIMEOUT_MS = 10_000;

export interface AcpRegistryState {
  index: AcpRegistryIndex;
  marks: Record<string, ProviderMark>;
  source: 'network' | 'cache' | 'snapshot';
  url: string;
  fetchedAt?: number;
  checkedAt?: number;
  etag?: string;
  error?: string;
  /** Agents or entries the parse skipped. */
  skipped: string[];
}

interface CacheMeta {
  url: string;
  etag?: string;
  fetchedAt?: number;
  checkedAt?: number;
}

interface IconCache {
  [id: string]: { url: string; mark: ProviderMark | null };
}

export interface AcpRegistrySnapshot {
  fetchedAt: number;
  registry: unknown;
  icons: Record<string, ProviderMark>;
}

/** The bundled snapshot (dynamic import, so it is loaded only when there is no cache). */
export async function loadBundledSnapshot(): Promise<AcpRegistrySnapshot> {
  const [registry, icons] = await Promise.all([
    import('./snapshot/acp-registry.snapshot.json', { with: { type: 'json' } }),
    import('./snapshot/acp-icons.snapshot.json', { with: { type: 'json' } }),
  ]);
  const r = registry.default as unknown as { fetchedAt?: number; registry?: unknown };
  return {
    fetchedAt: typeof r.fetchedAt === 'number' ? r.fetchedAt : 0,
    registry: r.registry,
    icons: (icons.default as unknown as { icons?: Record<string, ProviderMark> }).icons ?? {},
  };
}

export interface AcpRegistryCatalogOptions {
  /** `<server data dir>/acp/registry`. */
  cacheDir: string;
  /** Default: `GENERATORAI_ACP_REGISTRY_URL`, else the CDN index. */
  url?: string;
  fetchImpl?: typeof fetch;
  refreshIntervalMs?: number;
  /** Test seam for the bundled snapshot. */
  loadSnapshot?: () => Promise<AcpRegistrySnapshot>;
  logger?: { info?: (m: string) => void; warn?: (m: string) => void };
}

async function writeAtomic(file: string, body: string): Promise<void> {
  const tmp = `${file}.${process.pid}.${Date.now()}.tmp`;
  try {
    await writeFile(tmp, body, 'utf8');
    await rename(tmp, file);
  } catch (err) {
    await rm(tmp, { force: true }).catch(() => undefined);
    throw err;
  }
}

async function readJson<T>(file: string): Promise<T | null> {
  try {
    return JSON.parse(await readFile(file, 'utf8')) as T;
  } catch {
    return null;
  }
}

/** Read at most `max` bytes of a response body as text; null when it is larger. */
async function boundedText(res: Response, max: number): Promise<string | null> {
  const declared = Number(res.headers.get('content-length'));
  if (declared && declared > max) return null;
  const body = Buffer.from(await res.arrayBuffer());
  return body.length > max ? null : body.toString('utf8');
}

export class AcpRegistryCatalog {
  private readonly opts: AcpRegistryCatalogOptions;
  private readonly url: string;
  private state: AcpRegistryState | null = null;
  private inflight: Promise<AcpRegistryState> | null = null;
  private iconCache: IconCache = {};

  constructor(opts: AcpRegistryCatalogOptions) {
    this.opts = opts;
    this.url = opts.url ?? (process.env[ACP_REGISTRY_URL_ENV]?.trim() || ACP_REGISTRY_URL);
  }

  private file(name: string): string {
    return path.join(this.opts.cacheDir, name);
  }

  /** The disk cache, else the bundled snapshot. Never throws. */
  async load(): Promise<AcpRegistryState> {
    if (this.state) return this.state;
    const [meta, body, icons] = await Promise.all([
      readJson<CacheMeta>(this.file('meta.json')),
      readJson<unknown>(this.file('registry.json')),
      readJson<IconCache>(this.file('icons.json')),
    ]);
    this.iconCache = icons ?? {};
    if (meta && body && meta.url === this.url) {
      try {
        const { index, skipped } = parseAcpRegistry(body);
        this.state = {
          index,
          marks: this.marksFor(index, {}),
          source: 'cache',
          url: this.url,
          skipped,
          ...(meta.fetchedAt ? { fetchedAt: meta.fetchedAt } : {}),
          ...(meta.checkedAt ? { checkedAt: meta.checkedAt } : {}),
          ...(meta.etag ? { etag: meta.etag } : {}),
        };
        return this.state;
      } catch (err) {
        this.opts.logger?.warn?.(`[AcpRegistry] the cached index is unreadable, using the bundled snapshot: ${String(err)}`);
      }
    }
    this.state = await this.snapshotState();
    return this.state;
  }

  private async snapshotState(): Promise<AcpRegistryState> {
    try {
      const snap = await (this.opts.loadSnapshot ?? loadBundledSnapshot)();
      const { index, skipped } = parseAcpRegistry(snap.registry);
      return { index, marks: this.marksFor(index, snap.icons), source: 'snapshot', url: this.url, fetchedAt: snap.fetchedAt, skipped };
    } catch (err) {
      return { index: { version: '1.0.0', agents: [] }, marks: {}, source: 'snapshot', url: this.url, skipped: [], error: `No ACP registry snapshot: ${String(err)}` };
    }
  }

  /** Marks for the index's agents: fetched icons win, then the snapshot's. */
  private marksFor(index: AcpRegistryIndex, fallback: Record<string, ProviderMark>): Record<string, ProviderMark> {
    const out: Record<string, ProviderMark> = {};
    for (const agent of index.agents) {
      const cached = this.iconCache[agent.id];
      const mark = cached && (!agent.icon || cached.url === agent.icon) ? cached.mark : undefined;
      if (mark) out[agent.id] = mark;
      else if (fallback[agent.id]) out[agent.id] = fallback[agent.id]!;
    }
    return out;
  }

  /** Whether a background refresh is due (last network check older than the interval). */
  isStale(now = Date.now()): boolean {
    const checked = this.state?.checkedAt;
    return checked == null || now - checked >= (this.opts.refreshIntervalMs ?? ACP_REGISTRY_REFRESH_MS);
  }

  /**
   * Ask the network for a newer index (`If-None-Match`). Unless `force`, only when the last check is older than
   * the interval. Concurrent callers share one request. Never throws: a failure is `state.error`.
   */
  async refresh(force = false): Promise<AcpRegistryState> {
    const current = await this.load();
    if (!force && !this.isStale()) return current;
    this.inflight ??= this.fetchIndex(current).finally(() => { this.inflight = null; });
    return this.inflight;
  }

  private async fetchIndex(current: AcpRegistryState): Promise<AcpRegistryState> {
    const fetchImpl = this.opts.fetchImpl ?? fetch;
    const checkedAt = Date.now();
    try {
      const headers: Record<string, string> = { accept: 'application/json' };
      if (current.etag && current.source !== 'snapshot') headers['if-none-match'] = current.etag;
      const res = await fetchImpl(this.url, { headers, signal: AbortSignal.timeout(FETCH_TIMEOUT_MS) });
      if (res.status === 304) {
        this.state = { ...current, checkedAt, source: current.source === 'snapshot' ? 'snapshot' : 'cache' };
        delete this.state.error;
        await this.persistMeta();
        return this.state;
      }
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const text = await res.text();
      const { index, skipped } = parseAcpRegistry(JSON.parse(text));
      if (skipped.length) this.opts.logger?.warn?.(`[AcpRegistry] skipped ${skipped.length} entries: ${skipped.slice(0, 5).join('; ')}`);
      await mkdir(this.opts.cacheDir, { recursive: true });
      await writeAtomic(this.file('registry.json'), text);
      const etag = res.headers.get('etag') ?? undefined;
      await this.refreshIcons(index, fetchImpl);
      const snapshotMarks = current.source === 'snapshot' ? current.marks : {};
      this.state = {
        index,
        marks: this.marksFor(index, { ...snapshotMarks, ...current.marks }),
        source: 'network',
        url: this.url,
        fetchedAt: checkedAt,
        checkedAt,
        skipped,
        ...(etag ? { etag } : {}),
      };
      await this.persistMeta();
      this.opts.logger?.info?.(`[AcpRegistry] ${index.agents.length} agents from ${this.url}`);
      return this.state;
    } catch (err) {
      const message = err instanceof Error ? err.message : String(err);
      this.opts.logger?.warn?.(`[AcpRegistry] refresh failed: ${message}`);
      this.state = { ...current, checkedAt, error: `Could not refresh the ACP registry: ${message}` };
      await this.persistMeta().catch(() => undefined);
      return this.state;
    }
  }

  /** Fetch and sanitise icons that are new or moved; the rest are kept. */
  private async refreshIcons(index: AcpRegistryIndex, fetchImpl: typeof fetch): Promise<void> {
    const wanted = index.agents.filter((a) => a.icon && /^https?:\/\//.test(a.icon) && this.iconCache[a.id]?.url !== a.icon);
    await Promise.all(wanted.map(async (agent) => {
      try {
        const res = await fetchImpl(agent.icon!, { signal: AbortSignal.timeout(ICON_TIMEOUT_MS) });
        if (!res.ok) return;
        const svg = await boundedText(res, MAX_ICON_BYTES);
        this.iconCache[agent.id] = { url: agent.icon!, mark: svg ? sanitizeSvgIcon(svg) : null };
      } catch { /* keep the previous mark */ }
    }));
    for (const id of Object.keys(this.iconCache)) {
      if (!index.agents.some((a) => a.id === id)) delete this.iconCache[id];
    }
    if (wanted.length > 0) await writeAtomic(this.file('icons.json'), JSON.stringify(this.iconCache));
  }

  /** Only meaningful next to a cached body: a snapshot-only state keeps its throttle in memory. */
  private async persistMeta(): Promise<void> {
    const st = this.state;
    if (!st || st.source === 'snapshot') return;
    await mkdir(this.opts.cacheDir, { recursive: true });
    const meta: CacheMeta = {
      url: this.url,
      ...(st.etag ? { etag: st.etag } : {}),
      ...(st.fetchedAt ? { fetchedAt: st.fetchedAt } : {}),
      ...(st.checkedAt ? { checkedAt: st.checkedAt } : {}),
    };
    await writeAtomic(this.file('meta.json'), JSON.stringify(meta));
  }

  /** The current state (load() first). */
  get current(): AcpRegistryState | null {
    return this.state;
  }
}
