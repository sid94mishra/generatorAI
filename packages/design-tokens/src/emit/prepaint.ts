// ────────────────────────────────────────────────────────────────
// Pre-paint emitter (D-25; 02-design-system-spec.md §10.6, §11.2).
//
// `apps/web/index.html` carries an inline, dependency-free script in <head>
// that applies every appearance axis to <html> BEFORE the first paint:
//
//   class        light | dark        (mode resolved against the OS)
//   data-mode    system | light | dark
//   data-theme   theme id            (unknown → instrument)
//   data-accent  accent id           (unknown/absent → THE THEME'S default)
//   data-density comfortable | compact
//   data-font-size 12 | 13 | 14
//   data-motion  reduce              (stored "always", or the OS asks)
//   data-layout  mac | strip | native (desktop window chrome; native on the web)
//   + the desktop chrome classes and --gai-titlebar-* variables (06 §3.6)
//
// It is generated so its id lists, defaults and storage keys come from the
// registry and cannot drift; `readStoredAppearance()` (appearance.ts) is the
// same rule in TypeScript, and a parity test runs one against the other.
//
// The script is emitted on ONE line. The server and desktop CSPs pin it by
// SHA-256 over its exact bytes, and a single line has no line endings for
// `core.autocrlf` to rewrite on Windows, so the hash is the same on every OS.
// ────────────────────────────────────────────────────────────────

import { createHash } from 'node:crypto';

import {
  ACCENT_STORAGE_KEY,
  DEFAULT_DENSITY,
  DEFAULT_FONT_SIZE,
  DEFAULT_MODE,
  DENSITIES,
  DENSITY_STORAGE_KEY,
  FONT_SIZES,
  FONT_SIZE_STORAGE_KEY,
  MODES,
  MODE_STORAGE_KEY,
  REDUCE_MOTION_STORAGE_KEY,
  THEME_STORAGE_KEY,
} from '../registry.js';
import { REDUCE_MOTION_ON } from '../appearance.js';
import { ACCENT_IDS, DEFAULT_THEME, THEMES } from '../themes/index.js';

export const PREPAINT_START = '<!-- @generated-prepaint:start -->';
export const PREPAINT_END = '<!-- @generated-prepaint:end -->';

const j = (v: unknown): string => JSON.stringify(v);

/** The script body (the exact text between `<script>` and `</script>`). */
export function emitPrepaintScript(): string {
  const themeAccents = Object.fromEntries(THEMES.map((t) => [t.id, t.defaultAccent]));
  return [
    '(function(){',
    `var TA=${j(themeAccents)},M=${j(MODES.map((m) => m.id))},A=${j(ACCENT_IDS)},D=${j(DENSITIES)},F=${j(FONT_SIZES)};`,
    'function g(k){try{return localStorage.getItem(k)}catch(e){return null}}',
    'function q(s){try{return matchMedia(s).matches}catch(e){return false}}',
    `var m=g(${j(MODE_STORAGE_KEY)});if(M.indexOf(m)<0)m=${j(DEFAULT_MODE)};`,
    `var t=g(${j(THEME_STORAGE_KEY)});if(!Object.prototype.hasOwnProperty.call(TA,t))t=${j(DEFAULT_THEME)};`,
    `var a=g(${j(ACCENT_STORAGE_KEY)});if(A.indexOf(a)<0)a=TA[t];`,
    `var d=g(${j(DENSITY_STORAGE_KEY)});if(D.indexOf(d)<0)d=${j(DEFAULT_DENSITY)};`,
    `var f=g(${j(FONT_SIZE_STORAGE_KEY)});if(F.indexOf(f)<0)f=${j(DEFAULT_FONT_SIZE)};`,
    'var r=document.documentElement;',
    'r.classList.remove("light","dark");',
    'r.classList.add(m==="system"?(q("(prefers-color-scheme: dark)")?"dark":"light"):m);',
    'r.setAttribute("data-mode",m);r.setAttribute("data-theme",t);r.setAttribute("data-accent",a);',
    'r.setAttribute("data-density",d);r.setAttribute("data-font-size",f);',
    `if(g(${j(REDUCE_MOTION_STORAGE_KEY)})===${j(REDUCE_MOTION_ON)}||q("(prefers-reduced-motion: reduce)"))r.setAttribute("data-motion","reduce");`,
    // Desktop window chrome (06 §3.6): the preload exposes it synchronously, so
    // the title strip / traffic-light geometry is right on the first frame.
    // Mirrors applyChromeToDocument() in apps/web/src/lib/desktop.ts.
    'var c=null;try{c=window.generatoraiDesktop&&window.generatoraiDesktop.chrome}catch(e){}',
    'var s=c&&c.titleBarStyle;',
    'if(s){r.classList.add("platform-"+c.platform,"desktop-shell");',
    'if(s!=="native")r.classList.add("custom-titlebar");',
    'if(s==="overlay")r.classList.add("titlebar-overlay");',
    'if(s==="hidden-inset")r.classList.add("titlebar-inset");',
    'r.style.setProperty("--gai-titlebar-height",c.titleBarHeight+"px");',
    'r.style.setProperty("--gai-titlebar-inset-left",c.insetLeft+"px");',
    'r.style.setProperty("--gai-titlebar-inset-right",c.insetRight+"px");}',
    'r.setAttribute("data-layout",s==="overlay"?"strip":s==="hidden-inset"?"mac":"native");',
    '})();',
  ].join('');
}

/** The generated region of `apps/web/index.html`, markers included. */
export function emitPrepaint(): string {
  return [
    PREPAINT_START,
    '    <!-- Applies mode, theme, accent, density, font size and reduced motion before the',
    '         first paint (D-25). GENERATED by packages/design-tokens (emit/prepaint.ts); do not',
    '         edit. `pnpm tokens:write` also updates its CSP hash in apps/server (csp.ts) and',
    '         apps/desktop (session-hardening.ts). -->',
    `    <script>${emitPrepaintScript()}</script>`,
    `    ${PREPAINT_END}`,
  ].join('\n');
}

/** `sha256-<base64>` CSP source for the pre-paint script. */
export function prepaintCspHash(): string {
  return `sha256-${createHash('sha256').update(emitPrepaintScript(), 'utf8').digest('base64')}`;
}

/** Replace the marked region of index.html with a freshly generated one. */
export function splicePrepaint(html: string): string {
  const start = html.indexOf(PREPAINT_START);
  const end = html.indexOf(PREPAINT_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`apps/web/index.html is missing the ${PREPAINT_START} … ${PREPAINT_END} markers`);
  }
  return html.slice(0, start) + emitPrepaint() + html.slice(end + PREPAINT_END.length);
}
