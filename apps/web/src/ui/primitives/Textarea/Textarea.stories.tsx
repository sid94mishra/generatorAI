import { useState } from 'react';
import type { Meta, StoryObj } from '@storybook/react-vite';
import { expect, userEvent, waitFor } from 'storybook/test';
import { IconButton } from '../IconButton/IconButton.js';
import { Kbd } from '../Kbd/Kbd.js';
import { Textarea, type TextareaProps } from './Textarea.js';

const meta = {
  component: Textarea,
  tags: ['vrt-themes'],
  args: { 'aria-label': 'Review comment', placeholder: 'Leave a comment on this change', className: 'w-96' },
  argTypes: { variant: { control: 'inline-radio', options: ['md', 'prose', 'inline'] } },
} satisfies Meta<typeof Textarea>;

export default meta;
type Story = StoryObj<typeof meta>;

/** The task-box footer: attach on the left, a key hint on the right (KbdHintRow in the app). */
const taskFooter = (
  <>
    <IconButton icon="attach" label="Attach files" size="sm" />
    <span className="ml-auto flex items-center gap-1 text-micro text-fg-3">
      <Kbd keys={['Ctrl', '↵']} /> to start
    </span>
  </>
);

function Controlled(props: TextareaProps) {
  const [value, setValue] = useState(props.defaultValue?.toString() ?? '');
  return <Textarea {...props} defaultValue={undefined} value={value} onChange={(e) => setValue(e.target.value)} />;
}

export const Default: Story = {
  play: async ({ canvas }) => {
    const field = canvas.getByRole('textbox', { name: 'Review comment' });
    await userEvent.type(field, 'Looks good');
    await expect(field).toHaveValue('Looks good');
  },
};

/** variant × state (Components board "Inputs", ChatCreate task box). */
export const Matrix: Story = {
  render: () => (
    <div className="flex w-120 flex-col gap-3">
      <Textarea aria-label="md empty" placeholder="Leave a comment" />
      <Textarea aria-label="md filled" defaultValue={'Rename the helper and add a test.\nSecond line.'} />
      <Textarea aria-label="md invalid" defaultValue="Too short" invalid />
      <Textarea aria-label="md read only" readOnly defaultValue="Generated by the agent" />
      <Textarea aria-label="md disabled" disabled defaultValue="Disabled" />
      <Textarea variant="prose" aria-label="prose empty" placeholder="Describe the task…" />
      <Textarea variant="prose" aria-label="prose with footer" placeholder="Describe the task…" footer={taskFooter} />
      <Textarea variant="prose" aria-label="prose invalid" invalid defaultValue="Fix the flaky test" footer={taskFooter} />
      <Textarea variant="prose" aria-label="prose disabled" disabled defaultValue="Waiting for the run to finish" />
    </div>
  ),
};

export const Prose: Story = {
  args: { variant: 'prose', 'aria-label': 'Task', placeholder: 'Describe the task…', footer: taskFooter, className: 'w-120' },
};

/** Grows from 2 rows up to 4, then scrolls. */
export const Autosize: Story = {
  render: (args) => <Controlled {...args} autosize={{ minRows: 2, maxRows: 4 }} />,
  play: async ({ canvas }) => {
    const field = canvas.getByRole<HTMLTextAreaElement>('textbox', { name: 'Review comment' });
    const start = field.getBoundingClientRect().height;
    await userEvent.type(field, 'one{Enter}two{Enter}three');
    await waitFor(() => expect(field.getBoundingClientRect().height).toBeGreaterThan(start));
    const atThree = field.getBoundingClientRect().height;
    await userEvent.type(field, '{Enter}four{Enter}five{Enter}six{Enter}seven');
    await waitFor(() => expect(field.style.overflowY).toBe('auto'));
    // Capped at maxRows: taller than three lines, but no longer growing with every line.
    await expect(field.getBoundingClientRect().height).toBeGreaterThan(atThree);
    await expect(field.scrollHeight).toBeGreaterThan(field.clientHeight);
  },
};

export const AutosizeProse: Story = {
  render: (args) => <Controlled {...args} variant="prose" autosize footer={taskFooter} className="w-120" />,
};

export const Invalid: Story = {
  args: { invalid: true, defaultValue: 'Too short' },
  play: async ({ canvas }) => {
    await expect(canvas.getByRole('textbox', { name: 'Review comment' })).toHaveAttribute('aria-invalid', 'true');
  },
};

export const Disabled: Story = { args: { disabled: true, defaultValue: 'Read only for workers' } };

export const FocusVisible: Story = {
  args: { variant: 'prose', footer: taskFooter, className: 'w-120' },
  play: async ({ canvas }) => {
    await userEvent.tab();
    await expect(canvas.getByRole('textbox', { name: 'Review comment' })).toHaveFocus();
    await userEvent.tab();
    await expect(canvas.getByRole('button', { name: 'Attach files' })).toHaveFocus();
  },
};

export const Compact: Story = { globals: { density: 'compact' }, render: Matrix.render };

/** `inline`: the field inside a box that draws the chrome (the composer card). No border, fill or halo of its own. */
export const Inline: Story = {
  render: () => (
    <div className="w-120 rounded-dialog border border-line bg-raised px-3.5 pt-3 pb-2 focus-within:border-line-strong">
      <Controlled variant="inline" aria-label="Message" placeholder="Reply to Bug Fixer…" rows={1} />
    </div>
  ),
  play: async ({ canvas }) => {
    const field = canvas.getByRole('textbox', { name: 'Message' });
    await userEvent.type(field, 'Also check the rounding');
    await expect(field).toHaveValue('Also check the rounding');
  },
};
