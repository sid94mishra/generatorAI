#!/usr/bin/env node
// ────────────────────────────────────────────────────────────────
// Kit index for DESIGN_SYSTEM.md (P7-03).
//
// Lists every ui/ component (primitives, patterns, templates, shell) with its
// inventory ID from the file's header comment (`// P-02 Button (…)`), and every
// blocks/ folder with its public exports, then splices the tables between the
// `design-index` markers in DESIGN_SYSTEM.md. Storybook is the visual catalogue;
// this is the text index an agent or a reviewer greps.
//
//   node scripts/design-index.mjs           rewrite DESIGN_SYSTEM.md
//   node scripts/design-index.mjs --check   exit 1 when it is stale (CI)
// ────────────────────────────────────────────────────────────────

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(WEB, 'src');
const DOC = join(WEB, 'DESIGN_SYSTEM.md');
const START = '<!-- design-index:start — generated by `pnpm --filter @generatorai/web docs:design-index`; do not edit by hand -->';
const END = '<!-- design-index:end -->';

const KIT_GROUPS = [
  ['primitives', 'Primitives', '`@/ui/primitives/<Name>/<Name>.js`'],
  ['patterns', 'Patterns', '`@/ui/patterns/<Name>/<Name>.js`'],
  ['templates', 'Page templates', '`@/ui/templates/<Name>/<Name>.js`'],
  ['shell', 'Shell', '`@/ui/shell/<Name>/<Name>.js`'],
];

const dirs = (path) =>
  readdirSync(path, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith('_'))
    .map((e) => e.name)
    .sort((a, b) => a.localeCompare(b));

/** `// P-02 Button (03 §2 P-02; …)` → { id: 'P-02', title: 'Button' }. */
function kitHeader(file) {
  const line = readFileSync(file, 'utf8').split('\n').slice(0, 6).find((l) => /^\/\/ [A-Z]+-\d/.test(l));
  const m = line && /^\/\/ ([A-Z]+-\d+[a-z]?)\s+(.+?)(?:\s+\(|[.:—]|$)/.exec(line);
  return m ? { id: m[1], title: m[2].trim() } : null;
}

const hasStory = (dir, name) => existsSync(join(dir, `${name}.stories.tsx`));

function kitTables() {
  const out = [];
  for (const [folder, heading, importPath] of KIT_GROUPS) {
    const base = join(SRC, 'ui', folder);
    if (!existsSync(base)) continue;
    const rows = [];
    for (const name of dirs(base)) {
      const file = join(base, name, `${name}.tsx`);
      if (!existsSync(file)) continue;
      const header = kitHeader(file);
      rows.push(`| ${header?.id ?? '—'} | \`${name}\` | ${header && header.title !== name ? header.title : ''} | ${hasStory(join(base, name), name) ? '✓' : '—'} |`);
    }
    out.push(`### ${heading} (${rows.length}) — ${importPath}`, '', '| ID | Component | Inventory name | Story |', '|---|---|---|---|', ...rows, '');
  }
  return out;
}

/** A blocks/ folder's components (its PascalCase .tsx files) and the hooks its index.ts exports. */
function blockExports(dir) {
  const names = new Set(
    readdirSync(dir, { recursive: true })
      .filter((f) => typeof f === 'string' && /(^|\/)[A-Z]\w*\.tsx$/.test(f) && !/\.(test|stories)\.tsx$/.test(f) && !f.includes('__tests__'))
      .map((f) => f.split('/').pop().replace(/\.tsx$/, '')),
  );
  // Hook and column modules (`useEditorActions.ts`, `chatsColumns.tsx`).
  for (const f of readdirSync(dir, { recursive: true })) {
    if (typeof f !== 'string' || /\.(test|stories)\./.test(f) || f.includes('__tests__')) continue;
    const base = f.split('/').pop();
    if (/^use[A-Z]\w*\.tsx?$/.test(base) || /^\w+Columns\.tsx?$/.test(base)) names.add(base.replace(/\.tsx?$/, ''));
  }
  const index = join(dir, 'index.ts');
  if (existsSync(index)) {
    for (const m of readFileSync(index, 'utf8').matchAll(/\buse[A-Z]\w*/g)) names.add(m[0]);
  }
  return [...names].sort((x, y) => x.localeCompare(y));
}

function blockTable() {
  const base = join(SRC, 'blocks');
  const rows = dirs(base).map((name) => {
    const names = blockExports(join(base, name));
    const shown = names.slice(0, 14).map((n) => `\`${n}\``).join(', ');
    return `| \`blocks/${name}\` | ${shown}${names.length > 14 ? `, … (${names.length})` : ''} |`;
  });
  return ['### Blocks — query-aware parts shared by two or more features', '', '| Folder | Components |', '|---|---|', ...rows, ''];
}

const generated = [START, '', ...kitTables(), ...blockTable(), END].join('\n');
const doc = readFileSync(DOC, 'utf8');
const s = doc.indexOf(START);
const e = doc.indexOf(END);
if (s === -1 || e === -1) {
  console.error('[design-index] DESIGN_SYSTEM.md is missing the design-index markers.');
  process.exit(1);
}
const next = doc.slice(0, s) + generated + doc.slice(e + END.length);
if (process.argv.includes('--check')) {
  if (next !== doc) {
    console.error('[design-index] DESIGN_SYSTEM.md is stale — run `pnpm --filter @generatorai/web docs:design-index`.');
    process.exit(1);
  }
  console.log('[design-index] OK.');
} else {
  writeFileSync(DOC, next);
  console.log('[design-index] DESIGN_SYSTEM.md updated.');
}
